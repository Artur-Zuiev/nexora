-- Local-only application security audit events. No secrets or client content.
CREATE TABLE security_audit_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id VARCHAR(64) NOT NULL REFERENCES organizations(id),
  actor_username VARCHAR(120) NOT NULL,
  event_type VARCHAR(40) NOT NULL,
  target_username VARCHAR(120) NOT NULL,
  created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_security_audit_type CHECK (event_type IN (
    'MEMBER_CREATED', 'MEMBER_DISABLED', 'MEMBER_ENABLED',
    'MEMBER_PASSWORD_RESET', 'SELF_PASSWORD_CHANGED'
  ))
);
CREATE INDEX idx_security_audit_tenant_recent
  ON security_audit_events (tenant_id, created_at DESC, id DESC);
