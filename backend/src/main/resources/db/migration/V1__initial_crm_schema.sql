-- Baseline for fresh LOCAL development databases.
-- Existing Hibernate-created databases are baselined at V1 and run V2.
CREATE TABLE leads (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  email VARCHAR(255) NOT NULL,
  note VARCHAR(2000),
  status VARCHAR(255) NOT NULL
);

CREATE TABLE lead_tasks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lead_id BIGINT NOT NULL,
  title VARCHAR(160) NOT NULL,
  due_date DATE NOT NULL,
  status VARCHAR(20) NOT NULL,
  created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE lead_activities (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lead_id BIGINT NOT NULL,
  kind VARCHAR(40) NOT NULL,
  summary VARCHAR(200) NOT NULL,
  created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_lead_task_lead ON lead_tasks (lead_id);
CREATE INDEX idx_lead_task_due ON lead_tasks (due_date);
CREATE INDEX idx_lead_activity_lead ON lead_activities (lead_id);
